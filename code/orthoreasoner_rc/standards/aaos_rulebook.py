def score_rule(
    rule: RuleSpec,
    acuity: float,
    tear: float,
    goutallier: float,
    demand: float,
    inflammation: float,
) -> float:
    raw = (
        acuity * rule.acuity_weight
        + tear * rule.tear_weight
        + demand * rule.demand_weight
        + inflammation * rule.inflammation_weight
        - goutallier * rule.goutallier_weight
    )
    return raw - rule.threshold


def family_rules(family: str) -> tuple[RuleSpec, ...]:
    return tuple(rule for rule in RULES if rule.family == family)


def decision_rules(decision: str) -> tuple[RuleSpec, ...]:
    return tuple(rule for rule in RULES if rule.decision == decision)


def best_rule(
    acuity: float, tear: float, goutallier: float, demand: float, inflammation: float
) -> tuple[RuleSpec, float]:
    pairs = [
        (rule, score_rule(rule, acuity, tear, goutallier, demand, inflammation)) for rule in RULES
    ]
    return max(pairs, key=lambda item: item[1])
